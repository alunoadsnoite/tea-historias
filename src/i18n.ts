const index = { pt: 0, en: 1, es: 2, fr: 3 } as const;
export type Message = keyof typeof messages;

export function translate(language: Language, message: Message, values: Record<string, string | number> = {}) {
  return messages[message][index[language]].replace(/\{(\w+)\}/g, (placeholder, key: string) => {
    const value = values[key];
    return value === undefined ? placeholder : String(value);
  });
}
